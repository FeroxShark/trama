type Entrada = (typeof CANALES)[number];
/** Los nombres de las entradas de un tipo (para tipar el preload: `ipcRenderer.invoke` sólo con canales de acá). */
export type CanalDe<T extends Tipo> = Extract<Entrada, readonly [string, T, ...unknown[]]>[0];
export type CanalInvoke = CanalDe<"invoke">;
export type CanalEvento = CanalDe<"on">;
export type CanalEnvio = CanalDe<"send">;

const usoDe = (e: readonly [string, Tipo, Uso?]) => e[2];
const nombres = (f: (e: readonly [string, Tipo, Uso?]) => boolean) => (CANALES as readonly (readonly [string, Tipo, Uso?])[]).filter(f).map((e) => e[0]);

/** Lo que por red no se puede: salir de trama, y lo que abre o enfoca cosas en la pantalla de la PC. */
export const SOLO_VENTANA: readonly string[] = nombres((e) => usoDe(e) === "ventana" || usoDe(e) === "ventana-menos-local");
/** Lo que sigue vedado al navegador del modo local: lo de SOLO_VENTANA menos lo que ese navegador usa (consumo, borradores). */
export const SOLO_VENTANA_LOCAL: readonly string[] = nombres((e) => usoDe(e) === "ventana");
/** Los avisos que la carcasa de Windows le manda a la página. */
export const AVISOS_VENTANA: readonly string[] = nombres((e) => usoDe(e) === "aviso-ventana");
